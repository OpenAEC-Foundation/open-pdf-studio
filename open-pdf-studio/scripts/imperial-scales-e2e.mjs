import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { PDFDocument } from 'pdf-lib';
const pdf = await PDFDocument.create(); pdf.addPage([612, 792]);
const bytes = [...await pdf.save()];
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  await page.goto(process.argv[2] || 'http://127.0.0.1:3074', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('[data-tab="view"]').waitFor({ timeout: 90000 });
  await page.evaluate(async bytes => {
    const { cacheWebFile } = await import('/js/core/platform.js');
    const { createTab } = await import('/js/ui/chrome/tabs.js');
    const { loadPDFIfNeeded } = await import('/js/pdf/loader.js');
    const { getActiveDocument } = await import('/js/core/state.ts');
    const { createAnnotation } = await import('/js/annotations/factory.js');
    const { openDialog } = await import('/js/solid/stores/dialogStore.js');
    cacheWebFile('imperial.pdf', new Uint8Array(bytes));
    const { index } = createTab('imperial.pdf'); await loadPDFIfNeeded('imperial.pdf', index);
    const doc = getActiveDocument();
    doc.annotations.push(createAnnotation({ type: 'measureDistance', page: 1, startX: 10, startY: 20, endX: 190, endY: 20, measurePixels: 180 }));
    window.scaleTest = { doc, openDialog };
    openDialog('calibration', {});
  }, bytes);
  await page.locator('.calibration-tab').nth(1).click();
  assert.equal(await page.locator('.calibration-select-wide option[value="1:48"]').count(), 1, 'quarter-inch architectural preset is available');
  await page.locator('.calibration-select-wide').selectOption('1:48');
  const units = page.locator('.calibration-select').last();
  assert.equal(await units.inputValue(), 'ft');
  await page.locator('.calibration-dialog .pref-btn-primary').click();
  const result = () => page.evaluate(() => ({ scale: { ...window.scaleTest.doc.measureScale }, value: window.scaleTest.doc.annotations[0].measureValue }));
  let current = await result();
  assert.equal(current.scale.scaleRatio, '1:48'); assert.equal(current.scale.unit, 'ft');
  assert.ok(Math.abs(current.value - 10) < 1e-8);
  await page.evaluate(async () => { await (await import('/js/core/undo-manager.js')).undo(); });
  assert.equal(await page.evaluate(() => window.scaleTest.doc.measureScale), null);
  await page.evaluate(async () => { await (await import('/js/core/undo-manager.js')).redo(); });
  assert.equal((await result()).scale.scaleRatio, '1:48');
  await page.evaluate(async () => {
    const { loadDocumentScale } = await import('/js/annotations/measurement.js');
    window.scaleTest.doc.measureScale = null;
    loadDocumentScale(window.scaleTest.doc);
    window.scaleTest.openDialog('calibration', {});
  });
  assert.equal(await page.locator('.calibration-select-wide').inputValue(), '1:48');
  assert.equal(await units.inputValue(), 'ft');
  await page.locator('.calibration-select-wide').selectOption('1:240');
  await page.locator('.calibration-dialog .pref-btn-primary').click();
  current = await result(); assert.ok(Math.abs(current.value - 50) < 1e-8);
  await page.evaluate(() => window.scaleTest.openDialog('calibration', {}));
  await page.locator('.calibration-select-wide').selectOption('1:50');
  await units.selectOption('cm');
  await page.locator('.calibration-dialog .pref-btn-primary').click();
  current = await result(); assert.ok(Math.abs(current.value - 317.5) < 1e-8);
  await page.evaluate(() => window.scaleTest.openDialog('calibration', {}));
  await page.locator('.calibration-select-wide').selectOption('custom');
  await page.locator('.calibration-input-narrow').fill('64');
  await units.selectOption('in');
  await page.locator('.calibration-dialog .pref-btn-primary').click();
  current = await result(); assert.ok(Math.abs(current.value - 160) < 1e-8);
  console.log('PASS architectural/engineering/metric/custom scale selection, recalculation, persistence and undo/redo');
} finally { await browser.close(); }
